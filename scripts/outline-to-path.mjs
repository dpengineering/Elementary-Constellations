#!/usr/bin/env node
// Regenerate src/boxOutline.js (the built-in default cut outline) from a
// DXF or SVG template, using the same parser as the in-app outline settings.
//
// Usage:
//   npm run outline -- acrylic_template.svg
//   npm run outline -- new_template.dxf --units mm   # if the DXF has no $INSUNITS

import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseOutline } from "../src/outline.js";
import { VIEW_WIDTH, VIEW_HEIGHT } from "../src/boxOutline.js";

const args = process.argv.slice(2);
const unitsIdx = args.indexOf("--units");
const units = unitsIdx >= 0 ? args.splice(unitsIdx, 2)[1] : undefined;
const input = args[0];
if (!input || (units && !["mm", "cm", "in"].includes(units))) {
  console.error("usage: npm run outline -- <template.svg|template.dxf> [--units mm|cm|in]");
  process.exit(1);
}

let outline;
try {
  outline = parseOutline(readFileSync(input, "utf8"), input, {
    units,
    viewWidth: VIEW_WIDTH,
    viewHeight: VIEW_HEIGHT,
  });
} catch (e) {
  console.error(`error: ${e.message}`);
  process.exit(1);
}
for (const w of outline.warnings) console.warn(`warning: ${w}`);

const size = `${outline.widthIn.toFixed(3)} x ${outline.heightIn.toFixed(3)} in`;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "boxOutline.js");
writeFileSync(
  out,
  `// Default cut outline. Generated by scripts/outline-to-path.mjs from ${basename(input)};
// do not edit the path by hand. Re-run: npm run outline -- <template.svg|template.dxf>
// Outline size: ${size}, centered in the view below.

// View size in inches; must match WIDTH / HEIGHT in App.jsx.
export const VIEW_WIDTH = ${VIEW_WIDTH};
export const VIEW_HEIGHT = ${VIEW_HEIGHT};

export const BOX_OUTLINE_PATH =
  "${outline.d}";
`
);
console.log(`wrote ${out} (${size})`);
